export const fallbackMenuImage =
    "https://images.unsplash.com/photo-1546069901-ba9599a7e63c?auto=format&fit=crop&w=900&q=85";

export const getMenuImage = (name = "") => {
    // 1. Direct match check (exact dish name mapping)
    if (menuImages[name]) return menuImages[name];

    const lower = name.toLowerCase();

    // 2. Specific item keywords (checked BEFORE broad categories)
    if (lower.includes("veg biryani")) return menuImages["Veg Biryani"];
    if (lower.includes("chicken biryani")) return menuImages["Chicken Biryani"];
    if (lower.includes("biryani") || lower.includes("pulao") || lower.includes("fried rice")) return menuImages["Veg Biryani"];
    
    if (lower.includes("dal")) return menuImages["Dal Makhani"];
    if (lower.includes("naan") || lower.includes("roti") || lower.includes("paratha")) return menuImages["Garlic Naan"];
    if (lower.includes("dosa")) return menuImages["Masala Dosa"];
    if (lower.includes("gulab") || lower.includes("jamun")) return menuImages["Gulab Jamun"];
    if (lower.includes("lassi")) return menuImages["Mango Lassi"];

    if (lower.includes("farmhouse")) return menuImages["Farmhouse Pizza"];
    if (lower.includes("arrabbiata") || lower.includes("penne")) return menuImages["Penne Arrabbiata"];
    if (lower.includes("alfredo")) return menuImages["Alfredo Pasta"];
    if (lower.includes("lasagna")) return menuImages["Lasagna"];
    if (lower.includes("garlic bread")) return menuImages["Garlic Bread"];
    if (lower.includes("bruschetta")) return menuImages["Bruschetta"];
    if (lower.includes("risotto")) return menuImages["Mushroom Risotto"];
    if (lower.includes("lemonade")) return menuImages["Italian Lemonade"];

    // 3. Broad Category Fallbacks (Urban Bites and general queries)
    if (lower.includes("pizza")) return menuImages["Margherita Pizza"];
    if (lower.includes("burger")) return menuImages["Burger"];
    if (lower.includes("salad")) return menuImages["Salad"];
    if (lower.includes("steak") || lower.includes("meat") || lower.includes("kabab") || lower.includes("kebab") || lower.includes("lamb") || lower.includes("beef") || lower.includes("mutton")) return menuImages["Steak"];
    if (lower.includes("pasta") || lower.includes("spaghetti") || lower.includes("noodle") || lower.includes("macaroni")) return menuImages["Pasta"];
    if (lower.includes("tandoori")) return menuImages["Tandoori Chicken"];
    if (lower.includes("chicken") || lower.includes("murgh") || lower.includes("tikka")) return menuImages["Butter Chicken"];
    if (lower.includes("paneer") || lower.includes("cottage")) return menuImages["Paneer Tikka"];
    if (lower.includes("tiramisu") || lower.includes("cake") || lower.includes("sweet") || lower.includes("dessert") || lower.includes("pudding") || lower.includes("ice cream") || lower.includes("brownie")) return menuImages["Tiramisu"];
    if (lower.includes("soup") || lower.includes("shorba")) return menuImages["Soup"];
    if (lower.includes("curry") || lower.includes("masala") || lower.includes("gravy") || lower.includes("tadka")) return menuImages["Curry"];
    if (lower.includes("drink") || lower.includes("beverage") || lower.includes("coffee") || lower.includes("tea") || lower.includes("juice") || lower.includes("wine") || lower.includes("cocktail") || lower.includes("beer") || lower.includes("shake") || lower.includes("mocktail") || lower.includes("soda") || lower.includes("water")) return menuImages["Drinks"];

    return fallbackMenuImage;
};